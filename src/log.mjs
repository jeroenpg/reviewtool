// The review log: every round, page verdict and comment thread as Markdown, for a pull request comment.
import { execFileSync } from 'node:child_process';
import { threads } from './store.mjs';

export const MARKER = '<!-- reviewtool:log -->';
const LIMIT = 60_000; // GitHub caps a comment at 65,536 characters.
const VERDICT_TEXT = { approve: 'Approved', update: 'Needs update', revert: 'Revert' };

const date = (iso) => new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
const oneLine = (s) => s.replace(/\r?\n+/g, ' ⏎ ').replace(/\|/g, '\\|');
const quoteBody = (s, indent) => s.split(/\r?\n/).map((line, i) => (i === 0 ? line : indent + line)).join('\n');
const where = (c) => (c.pin ? `pinned on ${c.pin.img} (${c.pin.x}%, ${c.pin.y}%)` : 'general');

export function renderLog({ review, rounds, feedback }, { url = null, compactBefore = Infinity } = {}) {
  const all = threads(feedback.comments);
  const resolved = all.filter((t) => t.status === 'resolved').length;
  const latest = rounds.at(-1);
  const tally = { approve: 0, update: 0, revert: 0, none: 0 };
  for (const p of latest?.pages ?? []) tally[feedback.verdicts[`${latest.n}/${p.id}`]?.verdict ?? 'none']++;

  const out = [MARKER, `## Review log${review.title ? ` — ${review.title}` : ''}`, ''];
  out.push(
    `${rounds.length} round${rounds.length === 1 ? '' : 's'} · ${all.length} comment thread${all.length === 1 ? '' : 's'} (${resolved} resolved)` +
      (latest ? ` · latest round: ${tally.approve} approved, ${tally.update} need an update, ${tally.revert} revert, ${tally.none} without a verdict` : ''),
  );
  if (url) out.push('', `Review app: ${url}`);

  for (const round of [...rounds].reverse()) {
    const roundThreads = all.filter((t) => t.round === round.n);
    const compact = round.n < rounds.length - compactBefore + 1;
    out.push('', `<details${round === latest ? ' open' : ''}><summary><b>Round ${round.n}${round.title && round.title !== `Round ${round.n}` ? ` — ${round.title}` : ''}</b> · ${date(round.createdAt)} · ${round.pages.length} pages · ${roundThreads.length} comments</summary>`, '');
    if (round.notes) out.push(round.notes, '');
    out.push('| Page | Verdict | Comments |', '| --- | --- | --- |');
    for (const p of round.pages) {
      const v = feedback.verdicts[`${round.n}/${p.id}`]?.verdict;
      const n = roundThreads.filter((t) => t.page === p.id).length;
      out.push(`| ${oneLine(p.title)} | ${v ? VERDICT_TEXT[v] : '—'} | ${n || ''} |`);
    }
    if (!compact) {
      for (const p of round.pages) {
        const pageThreads = roundThreads.filter((t) => t.page === p.id);
        if (!pageThreads.length) continue;
        out.push('', `**${p.title}**${p.route ? ` \`${p.route}\`` : ''}`, '');
        for (const t of pageThreads) {
          out.push(`- **${t.author}** (${where(t)}${t.status === 'resolved' ? ', resolved' : ''}): ${quoteBody(t.text, '  ')}`);
          for (const r of t.replies) out.push(`  - **${r.author}**: ${quoteBody(r.text, '    ')}`);
        }
      }
    } else if (roundThreads.length) {
      out.push('', `_${roundThreads.length} comments in this round are left out to keep the log under GitHub's size limit; see the review app._`);
    }
    out.push('', '</details>');
  }
  out.push('', `<sub>Generated by [reviewtool](https://github.com/jeroenpg/reviewtool) on ${date(new Date().toISOString())}.</sub>`, '');
  const md = out.join('\n');
  // Too long for one comment: keep the newest rounds in full and only the tables of older ones.
  if (md.length > LIMIT && compactBefore > 1) return renderLog({ review, rounds, feedback }, { url, compactBefore: Math.min(compactBefore, rounds.length) - 1 });
  return md;
}

function gh(args, input) {
  return execFileSync('gh', args, { input, encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] });
}

/** Creates the log comment on the pull request, or updates the one posted earlier (found by its marker). */
export function postLog(markdown, { repo, pr }) {
  if (!repo || !pr) throw new Error('posting needs the repository and pull request: set them with reviewtool init/set --repo owner/name --pr N, or pass --repo and --pr');
  const ids = gh(['api', '--paginate', `repos/${repo}/issues/${pr}/comments`, '--jq', `.[] | select(.body | startswith("${MARKER}")) | .id`])
    .split('\n')
    .filter(Boolean);
  const body = JSON.stringify({ body: markdown });
  if (ids.length) {
    const res = JSON.parse(gh(['api', '-X', 'PATCH', `repos/${repo}/issues/comments/${ids[0]}`, '--input', '-'], body));
    return { action: 'updated', url: res.html_url };
  }
  const res = JSON.parse(gh(['api', '-X', 'POST', `repos/${repo}/issues/${pr}/comments`, '--input', '-'], body));
  return { action: 'created', url: res.html_url };
}
